#!/usr/bin/env bash
# Creates the lab's secrets once, on this machine only (both are git-ignored):
#   lab.env  - random passwords and keys (format: lab.env.example)
#   pki/     - internal certificate authority + TLS certificates (www, intranet, app, db)
# Safe to run again: existing values and files are kept, missing ones are added. deploy.sh runs it before every
# deploy. ("RAM\+": a bare + splits an OpenSSL subject field.)
cd "$(dirname "$0")/.."
rnd() { openssl rand -hex "${1:-12}"; }

[ -f lab.env ] || { echo "# Generated by scripts/gen-secrets.sh on $(date +%F) - never commit this file." > lab.env; chmod 600 lab.env; }
ensure() {  # KEY VALUE: add the key if it is missing
  grep -q "^$1=" lab.env || { echo "$1=$2" >> lab.env; echo "[gen-secrets] lab.env: $1 added"; }
}
ensure DB_WEB_PASS "$(rnd)"
ensure DB_APP_PASS "$(rnd)"
ensure DB_REPL_PASS "$(rnd)"
ensure DB_BACKUP_PASS "$(rnd)"
ensure ZBX_DB_PASS "$(rnd)"
ensure ZBX_ADMIN_PASS "$(rnd)"
ensure ZBX_PSK "$(rnd 32)"                 # Zabbix server <-> agent encryption (TLS PSK, 256 bit)
ensure SNMP_AUTH_PASS "$(rnd)"             # SNMPv3 user "zabbix" on the switches (SHA + AES)
ensure SNMP_PRIV_PASS "$(rnd)"
ensure RADIUS_SECRET "$(rnd)"              # switches <-> FreeRADIUS on ad01
ensure SWITCH_LOCAL_PASS "$(rnd)"          # local "admin" on the switches: break-glass only, when RADIUS is down
# network administrators log in to the switches through RADIUS (scripts/secure-switches.sh)
if grep -q '^SWITCH_USER=admin$' lab.env; then        # older lab.env: switch to the RADIUS account
  sed -i '/^SWITCH_USER=/d; /^SWITCH_PASS=/d' lab.env; echo "[gen-secrets] lab.env: switch login moved to RADIUS (netadmin)"
fi
ensure SWITCH_USER netadmin
ensure SWITCH_PASS "$(rnd)"

cert() {  # name, CN, subjectAltName list: signed by the lab CA if missing
  [ -s "pki/$1.crt" ] && return
  openssl req -newkey rsa:2048 -nodes -subj "/O=RAM\+ Data Center/CN=$2" -keyout "pki/$1.key" -out "pki/$1.csr" 2>/dev/null
  printf 'subjectAltName=%s\nextendedKeyUsage=serverAuth\n' "$3" > "pki/$1.ext"
  openssl x509 -req -in "pki/$1.csr" -CA pki/ca.crt -CAkey pki/ca.key -CAcreateserial -days 825 \
    -extfile "pki/$1.ext" -out "pki/$1.crt" 2>/dev/null
  rm -f "pki/$1.csr" "pki/$1.ext" pki/ca.srl
  chmod 600 "pki/$1.key"
  [ -s "pki/$1.crt" ] || { echo "[gen-secrets] ERROR: certificate $1 failed"; exit 1; }
  echo "[gen-secrets] pki/$1.crt issued for $2"
}
mkdir -p pki && chmod 700 pki
if [ ! -s pki/ca.crt ]; then
  openssl req -x509 -newkey rsa:3072 -nodes -days 3650 -subj "/O=RAM\+ Data Center/CN=RAM\+ Lab Root CA" \
    -keyout pki/ca.key -out pki/ca.crt 2>/dev/null
  chmod 600 pki/ca.key
  [ -s pki/ca.crt ] || { echo "[gen-secrets] ERROR: CA generation failed"; rm -rf pki; exit 1; }
  echo "[gen-secrets] pki/ca.crt: RAM+ Lab Root CA created"
fi
cert www www.dc.lab "DNS:www.dc.lab,DNS:dc.lab,IP:10.10.60.20,IP:10.0.0.1,IP:10.0.0.5"
cert intranet intranet.dc.lab "DNS:intranet.dc.lab,DNS:web01.dc.lab,DNS:web02.dc.lab,IP:10.10.20.12,IP:10.10.20.10,IP:10.10.20.11"
cert app app.dc.lab "DNS:app.dc.lab,DNS:app01.dc.lab,DNS:app02.dc.lab,IP:10.10.20.22,IP:10.10.20.20,IP:10.10.20.21"
cert db db.dc.lab "DNS:db.dc.lab,DNS:db01.dc.lab,DNS:db02.dc.lab,IP:10.10.20.35,IP:10.10.20.30,IP:10.10.20.31"
exit 0
